class Token:
    """Один токен: тип, значение и позиция."""

    __slots__ = ("type", "value", "line", "col")

    def __init__(self, t, v, l, c):
        self.type = t
        self.value = v
        self.line = l
        self.col = c

    def __repr__(self):  # удобно в отладке/тестах
        return f"Token({self.type}, {self.value!r}, {self.line}:{self.col})"
