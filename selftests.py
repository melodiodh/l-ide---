def run_self_tests(tests=None, verbose=False):
    """Прогоняет тесты и возвращает список (имя, успех, текст_ошибки)."""
    results = []
    for name, code, expected in (tests or SELF_TESTS):
        buf = io.StringIO()
        interp = Interpreter(
            output=lambda s: buf.write(s),
            input_reader=lambda p="": "",
        )
        try:
            interp.run(code)
            actual = buf.getvalue()
            if actual == expected:
                results.append((name, True, ""))
            else:
                results.append(
                    (name, False, f"ожидалось {expected!r}, получено {actual!r}")
                )
        except Exception as e:
            results.append((name, False, f"{type(e).__name__}: {e}"))
        if verbose:
            ok = results[-1][1]
            print(("  ok   " if ok else "  FAIL ") + name)
    return results


def main():
    results = run_self_tests()
    passed = sum(1 for _, ok, _ in results if ok)
    total = len(results)
    for name, ok, err in results:
        if not ok:
            print(f"FAIL  {name}: {err}")
    print(f"\n{passed}/{total} тестов прошло")
    return 0 if passed == total else 1


if __name__ == "__main__":
    raise SystemExit(main())
